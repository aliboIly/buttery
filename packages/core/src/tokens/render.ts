type Declaration = readonly [name: string, value: string];

const HEADER =
  "/* Generated by packages/core/scripts/generate-tokens.ts from src/tokens. Edit the TypeScript source, then run pnpm tokens. */";

function px(value: number): string {
  return value === 0 ? "0" : `${String(value)}px`;
}

function ms(value: number): string {
  return `${String(value)}ms`;
}

function block(
  selector: string,
  declarations: readonly Declaration[],
  indent = "  ",
): string {
  const body = declarations
    .map(([name, value]) => `${indent}  ${name}: ${value};`)
    .join("\n");
  return `${indent}${selector} {\n${body}\n${indent}}`;
}

function themeDeclarations(scheme: ColorScheme): Declaration[] {
  return [
    ["color-scheme", scheme],
    ...Object.entries(colors).map(([name, definition]): Declaration => [
      `--bt-${name}`,
      definition[scheme],
    ]),
    ...Object.entries(shadows).map(([name, definition]): Declaration => [
      `--bt-${name}`,
      definition[scheme],
    ]),
  ];
}

function heightDeclarations(density: Density): Declaration[] {
  return Object.entries(heights).map(([name, definition]): Declaration => [
    `--bt-h-${name}`,
    px(definition[density]),
  ]);
}

function textRoleDeclarations(
  name: string,
  role: TextRoleDefinition,
): Declaration[] {
  return [
    [`--bt-text-${name}-size`, px(role.size)],
    [`--bt-text-${name}-line`, px(role.lineHeight)],
    [`--bt-text-${name}-weight`, String(role.weight)],
    [
      `--bt-text-${name}-tracking`,
      `var(--bt-tracking-${trackingFor(role.size, role.weight)})`,
    ],
  ];
}

function sharedDeclarations(): Declaration[] {
  const spaceSteps = Object.keys(space) as SpaceStep[];
  return [
    ["--bt-font-sans", fontFamilies.sans],
    ["--bt-font-mono", fontFamilies.mono],
    ...Object.entries(tracking).map(([name, value]): Declaration => [
      `--bt-tracking-${name}`,
      value,
    ]),
    ...spaceSteps.map((step): Declaration => [spaceVar(step), px(space[step])]),
    ["--bt-space-well", px(spaceWell)],
    ...Object.entries(radii).map(([name, value]): Declaration => [
      `--bt-r-${name}`,
      px(value),
    ]),
    ...Object.values(widths).map((definition): Declaration => [
      definition.cssVar,
      px(definition.value),
    ]),
    ...Object.entries(zIndex).map(([name, value]): Declaration => [
      `--bt-z-${name}`,
      String(value),
    ]),
    ...Object.entries(durations).map(([name, value]): Declaration => [
      `--bt-dur-${name}`,
      ms(value),
    ]),
    ...Object.entries(easings).map(([name, value]): Declaration => [
      `--bt-ease-${name}`,
      value,
    ]),
    ...Object.entries(timing).map(([name, value]): Declaration => [
      `--bt-${name}`,
      ms(value),
    ]),
    ["--bt-press-scale", String(pressScale)],
    ["--bt-icon-stroke", String(iconStroke)],
    ...Object.entries(textRoles).flatMap(([name, role]) =>
      textRoleDeclarations(name, role),
    ),
    ...Object.entries(displayRoles).flatMap(([name, role]) =>
      (Object.keys(role.steps) as DisplayStep[]).flatMap(
        (step): Declaration[] => {
          const [size, lineHeight] = role.steps[step];
          return [
            [`--bt-text-${name}-size-${step}`, px(size)],
            [`--bt-text-${name}-line-${step}`, px(lineHeight)],
            [
              `--bt-text-${name}-tracking-${step}`,
              `var(--bt-tracking-${trackingFor(size, role.weight)})`,
            ],
          ];
        },
      ),
    ),
  ];
}

/** The `bt.tokens` layer: light and dark themes, shared scales, and both densities. */
export function renderTokensCss(): string {
  const dark = themeDeclarations("dark");
  return [
    HEADER,
    "@layer bt.tokens {",
    block(':root,\n  [data-bt-theme="light"]', themeDeclarations("light")),
    "",
    block(":root", sharedDeclarations()),
    "",
    block(
      ':root,\n  [data-bt-density="comfortable"]',
      heightDeclarations("comfortable"),
    ),
    "",
    block('[data-bt-density="compact"]', heightDeclarations("compact")),
    "",
    block('[data-bt-theme="dark"]', dark),
    "",
    "  @media (prefers-color-scheme: dark) {",
    block(':root:not([data-bt-theme="light"])', dark, "    "),
    "  }",
    "}",
    "",
  ].join("\n");
}

function roleSelector(name: string): string {
  return `.bt-text[data-role="${name}"]`;
}

/** The text-role recipe, built from the same role table as the tokens. */
export function renderTextRecipeCss(): string {
  const roleBlocks = Object.entries(textRoles).map(
    ([name, role]: [string, TextRoleDefinition]) => {
      const declarations: Declaration[] = [
        ["font-size", `var(--bt-text-${name}-size)`],
        ["line-height", `var(--bt-text-${name}-line)`],
        ["font-weight", `var(--bt-text-${name}-weight)`],
        ["letter-spacing", `var(--bt-text-${name}-tracking)`],
      ];
      if (role.color) declarations.push(["color", `var(--bt-${role.color})`]);
      if (role.tabular)
        declarations.push(["font-variant-numeric", "tabular-nums"]);
      return block(roleSelector(name), declarations);
    },
  );

  const displaySizes = (name: string, step: DisplayStep): Declaration[] => [
    ["font-size", `var(--bt-text-${name}-size-${step})`],
    ["line-height", `var(--bt-text-${name}-line-${step})`],
    ["letter-spacing", `var(--bt-text-${name}-tracking-${step})`],
  ];

  const displayBlocks = Object.entries(displayRoles).map(([name, role]) =>
    block(roleSelector(name), [
      ["font-weight", String(role.weight)],
      ["color", `var(--bt-${role.color})`],
      ["text-wrap", "balance"],
      ...displaySizes(name, "sm"),
    ]),
  );

  const displayStep = (step: DisplayStep): string[] =>
    Object.keys(displayRoles).map((name) =>
      block(roleSelector(name), displaySizes(name, step), "    "),
    );

  const trimmed = [
    ...Object.entries(textRoles)
      .filter(([, role]: [string, TextRoleDefinition]) => role.trim === true)
      .map(([name]) => name),
    ...Object.keys(displayRoles),
  ];
  const trimSelector = `.bt-text:is(${trimmed.map((name) => `[data-role="${name}"]`).join(", ")}):not(.bt-truncate)`;

  return [
    HEADER,
    "@layer bt.recipes {",
    roleBlocks.join("\n\n"),
    "",
    displayBlocks.join("\n\n"),
    "",
    `  @container (width >= ${px(displayBreakpoints.md)}) {`,
    displayStep("md").join("\n\n"),
    "  }",
    "",
    `  @container (width >= ${px(displayBreakpoints.lg)}) {`,
    displayStep("lg").join("\n\n"),
    "  }",
    "",
    block(trimSelector, [["text-box", "trim-both cap alphabetic"]]),
    "}",
    "",
  ].join("\n");
}

function hexOf(value: string): string | undefined {
  return value.startsWith("#") ? value : undefined;
}

/** Every token with its CSS variable, values per theme and density, and what it's for. */
export function renderTokensJson(): string {
  const pairs = contrastPairs.map((pair) => {
    const ratio = (scheme: ColorScheme): number | null => {
      const text = hexOf(colors[pair.text][scheme]);
      const background = hexOf(colors[pair.on][scheme]);
      return text && background
        ? Number(contrastRatio(text, background).toFixed(2))
        : null;
    };
    return {
      text: `--bt-${pair.text}`,
      on: `--bt-${pair.on}`,
      minimum: pair.minimum,
      light: ratio("light"),
      dark: ratio("dark"),
    };
  });

  const json = {
    color: Object.fromEntries(
      Object.entries(colors).map(([name, definition]) => [
        name,
        { cssVar: `--bt-${name}`, ...definition },
      ]),
    ),
    shadow: Object.fromEntries(
      Object.entries(shadows).map(([name, definition]) => [
        name,
        { cssVar: `--bt-${name}`, ...definition },
      ]),
    ),
    space: {
      ...Object.fromEntries(
        (Object.keys(space) as SpaceStep[]).map((step) => [
          step,
          { cssVar: spaceVar(step), value: px(space[step]) },
        ]),
      ),
      well: { cssVar: "--bt-space-well", value: px(spaceWell) },
    },
    height: Object.fromEntries(
      Object.entries(heights).map(([name, definition]) => [
        name,
        {
          cssVar: `--bt-h-${name}`,
          comfortable: px(definition.comfortable),
          compact: px(definition.compact),
          description: definition.description,
        },
      ]),
    ),
    width: Object.fromEntries(
      Object.entries(widths).map(([name, definition]) => [
        name,
        {
          cssVar: definition.cssVar,
          value: px(definition.value),
          description: definition.description,
        },
      ]),
    ),
    radius: Object.fromEntries(
      Object.entries(radii).map(([name, value]) => [
        name,
        { cssVar: `--bt-r-${name}`, value: px(value) },
      ]),
    ),
    z: Object.fromEntries(
      Object.entries(zIndex).map(([name, value]) => [
        name,
        { cssVar: `--bt-z-${name}`, value },
      ]),
    ),
    duration: Object.fromEntries(
      Object.entries(durations).map(([name, value]) => [
        name,
        { cssVar: `--bt-dur-${name}`, value: ms(value) },
      ]),
    ),
    easing: Object.fromEntries(
      Object.entries(easings).map(([name, value]) => [
        name,
        { cssVar: `--bt-ease-${name}`, value },
      ]),
    ),
    timing: Object.fromEntries(
      Object.entries(timing).map(([name, value]) => [
        name,
        { cssVar: `--bt-${name}`, value: ms(value) },
      ]),
    ),
    spring,
    font: Object.fromEntries(
      Object.entries(fontFamilies).map(([name, value]) => [
        name,
        { cssVar: `--bt-font-${name}`, value },
      ]),
    ),
    text: Object.fromEntries(
      Object.entries(textRoles).map(
        ([name, role]: [string, TextRoleDefinition]) => [
          name,
          {
            size: px(role.size),
            lineHeight: px(role.lineHeight),
            weight: role.weight,
            tracking: `--bt-tracking-${trackingFor(role.size, role.weight)}`,
            color: role.color ? `--bt-${role.color}` : null,
            tabular: role.tabular ?? false,
            trim: role.trim ?? false,
            description: role.description,
          },
        ],
      ),
    ),
    display: Object.fromEntries(
      Object.entries(displayRoles).map(([name, role]) => [
        name,
        {
          steps: Object.fromEntries(
            (Object.keys(role.steps) as DisplayStep[]).map((step) => {
              const [size, lineHeight] = role.steps[step];
              return [
                step,
                {
                  size: px(size),
                  lineHeight: px(lineHeight),
                  tracking: `--bt-tracking-${trackingFor(size, role.weight)}`,
                },
              ];
            }),
          ),
          weight: role.weight,
          color: `--bt-${role.color}`,
          description: role.description,
        },
      ]),
    ),
    contrastPairs: pairs,
  };
  return `${JSON.stringify(json, null, 2)}\n`;
}

