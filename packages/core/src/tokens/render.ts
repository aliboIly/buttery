/** The Tailwind v4 bridge. `@theme inline` keeps utilities pointing at buttery's variables, so nested themes work. */
export function renderTailwindCss(): string {
  const declarations: Declaration[] = [
    ...TAILWIND_COLORS.map(([name, token]): Declaration => [
      `--color-${name}`,
      `var(--bt-${token})`,
    ]),
    ["--font-sans", "var(--bt-font-sans)"],
    ["--font-mono", "var(--bt-font-mono)"],
    ...Object.keys(radii)
      .filter((name) => name !== "full")
      .map((name): Declaration => [`--radius-${name}`, `var(--bt-r-${name})`]),
    ["--radius-card", "var(--bt-r-lg)"],
    ["--radius-section", "var(--bt-r-2xl)"],
    ["--radius-panel", "var(--bt-r-3xl)"],
    ...TAILWIND_SHADOWS.map((token): Declaration => [
      `--${token}`,
      `var(--bt-${token})`,
    ]),
    ["--inset-shadow-hairline", "var(--bt-shadow-inset)"],
    ["--spacing-well", "var(--bt-space-well)"],
    ...TAILWIND_HEIGHTS.map(([name, token]): Declaration => [
      `--spacing-${name}`,
      `var(--bt-h-${token})`,
    ]),
    ["--container-inspector", "var(--bt-w-inspector)"],
    ["--container-dialog", "var(--bt-w-dialog)"],
    ["--container-menu-min", "var(--bt-w-menu-min)"],
    ["--container-page", "var(--bt-w-page)"],
    ["--container-shell", "var(--bt-w-shell-max)"],
    ...Object.keys(textRoles).flatMap((name): Declaration[] => [
      [`--text-${name}`, `var(--bt-text-${name}-size)`],
      [`--text-${name}--line-height`, `var(--bt-text-${name}-line)`],
      [`--text-${name}--font-weight`, `var(--bt-text-${name}-weight)`],
      [`--text-${name}--letter-spacing`, `var(--bt-text-${name}-tracking)`],
    ]),
    ["--ease-buttery", "var(--bt-ease-standard)"],
    ["--ease-buttery-out", "var(--bt-ease-out)"],
    ["--ease-buttery-in", "var(--bt-ease-in)"],
  ];
  return [HEADER, block("@theme inline", declarations, ""), ""].join("\n");
}

function paddingValue(padding: readonly (SpaceStep | "well")[]): string {
  return padding
    .map((step) =>
      step === "well" ? "var(--bt-space-well)" : `var(${spaceVar(step)})`,
    )
    .join(" ");
}

/** The surface recipe, built from the surface level table. */
export function renderSurfaceRecipeCss(): string {
  const levels = Object.entries(surfaces).map(
    ([level, surface]: [string, SurfaceDefinition]) => {
      const declarations: Declaration[] = [
        ["--bt-surface-bg", `var(--bt-${surface.background})`],
        [
          "--bt-surface-radius",
          surface.radius === "none" ? "0" : `var(--bt-r-${surface.radius})`,
        ],
        [
          "--bt-surface-shadow",
          surface.shadow ? `var(--bt-${surface.shadow})` : "none",
        ],
        [
          "--bt-surface-padding",
          surface.padding ? paddingValue(surface.padding) : "0",
        ],
      ];
      if (surface.border)
        declarations.push(["border", `1px solid var(--bt-${surface.border})`]);
      return block(`.bt-surface[data-level="${level}"]`, declarations);
    },
  );
  return [
    HEADER,
    "@layer bt.recipes {",
    block(".bt-surface", [
      ["min-inline-size", "0"],
      ["border-radius", "var(--bt-surface-radius, var(--bt-r-lg))"],
      ["background-color", "var(--bt-surface-bg, var(--bt-bg-surface))"],
      ["box-shadow", "var(--bt-surface-shadow, none)"],
      ["padding", "var(--bt-surface-padding, 0)"],
    ]),
    "",
    levels.join("\n\n"),
    "}",
    "",
  ].join("\n");
}

/** Attribute rules for the flow primitives' spacing props and the layer bands. */
export function renderLayoutCss(): string {
  const steps = (Object.keys(space) as SpaceStep[]).sort(
    (a, b) => space[a] - space[b],
  );
  const spacing: readonly (readonly [attribute: string, property: string])[] = [
    ["data-gap", "gap"],
    ["data-pad", "padding"],
    ["data-pad-x", "padding-inline"],
    ["data-pad-y", "padding-block"],
  ];
  const spacingBlocks = spacing.flatMap(([attribute, property]) =>
    steps.map((step) =>
      block(`[data-bt][${attribute}="${step}"]`, [
        [property, `var(${spaceVar(step)})`],
      ]),
    ),
  );
  const layerBlocks = layerBands.map((band) =>
    block(`[data-bt-layer="${band}"]`, [["z-index", `var(--bt-z-${band})`]]),
  );
  return [
    HEADER,
    "@layer bt.primitives {",
    [...spacingBlocks, ...layerBlocks].join("\n\n"),
    "}",
    "",
  ].join("\n");
}
